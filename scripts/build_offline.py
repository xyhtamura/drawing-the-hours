"""Generate the offline cache inventory. Run before publishing: python scripts/build_offline.py.

Only the kiosk's runtime files are cached; recorded audition audio and archived
video clips stay out. --check fails if the committed inventory is stale.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    paths = [ROOT / name for name in ('index.html', 'style.css', 'ui.css', 'favicon.svg', 'manifest.webmanifest')]
    for folder in ('src', 'assets', 'somewarez'):
        paths.extend(p for p in (ROOT / folder).rglob('*') if p.is_file()
                     and p.suffix.lower() in {'.js', '.css', '.svg', '.png', '.jpg', '.webp', '.ttf', '.woff2'}
                     and 'audio-local' not in p.parts
                     # link-preview cards; the game never loads them (1.1 MB)
                     and not p.name.startswith('drawing-the-hours-embed.'))
    paths = sorted(set(paths))
    digest = hashlib.sha256()
    names = []
    for path in paths:
        name = './' + path.relative_to(ROOT).as_posix()
        names.append(name)
        digest.update(name.encode())
        digest.update(path.read_bytes())
    version = digest.hexdigest()[:16]
    content = ('// Generated by scripts/build_offline.py; do not edit.\n'
               'const OFFLINE_PREFIX = "drawing-the-hours:" + self.registration.scope + ":";\n'
               f'const OFFLINE_CACHE = OFFLINE_PREFIX + "{version}";\n'
               f'const OFFLINE_FILES = {json.dumps(names, indent=2)};\n'
               'importScripts("./somewarez/offline-worker.js");\n')
    target = ROOT / 'offline-sw.js'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            raise SystemExit('Offline inventory is stale. Run python scripts/build_offline.py.')
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
    print(f'Offline inventory: {len(names)} files, version {version}')

if __name__ == '__main__':
    main()
