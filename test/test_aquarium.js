import assert from 'node:assert/strict';
import {judgeStroke} from '../aquarium/rules.js';
import {LEVELS} from '../aquarium/levels.js';
const loop=[{x:60,y:60},{x:200,y:60},{x:200,y:200},{x:60,y:200},{x:60,y:60}];
const figure=[{x:250,y:250},{x:100,y:100},{x:60,y:250},{x:100,y:400},{x:250,y:250},{x:400,y:100},{x:440,y:250},{x:400,y:400},{x:250,y:250}];
const fish=(kind='bangus',x=120,y=120)=>({kind,x,y});
const judge=(fs,l=LEVELS[0],hs=[],ps=[],s=true,points=loop)=>judgeStroke(points,fs,hs,ps,l,s);
assert.equal(judge([fish()]).guided.length,1);
assert.match(judge([fish()],LEVELS[0],[],[],true,loop.slice(0,3)).error,/close/);
assert.match(judge([fish(),fish('fry')],LEVELS[1]).error,/Fry/);
assert.match(judge([fish()],LEVELS[0],[{x:60,y:100,cuts:true,radius:22}]).error,/touched/);
assert.match(judge([fish()],LEVELS[0],[{kind:'root',x:60,y:10,endY:300,cuts:true,radius:22}]).error,/touched/);
assert.match(judge([fish()],LEVELS[3],[{x:120,y:120,cuts:false,radius:22}]).error,/netting/);
assert.match(judge([fish('sardine')],LEVELS[2]).error,/at least 3/);
assert.equal(judge([fish('sardine'),fish('sardine',140),fish('sardine',150)],LEVELS[2]).guided.length,3);
assert.match(judge([fish(),fish('tilapia')],LEVELS[7]).error,/own pocket/);
assert.match(judge([fish(),fish('bangus',140)],LEVELS[5],[],[],false).error,/Slack/);
assert.equal(judge([fish(),fish('bangus',140)],LEVELS[5]).guided.length,2);
assert.equal(judge([],LEVELS[5],[],[{kind:'bubble',x:120,y:120}],false).taken.length,1);
assert.equal(judge([{...fish(),safe:true}]).error,'The loop held only water. Try a fish or a pickup.');
assert.match(judge([fish()],LEVELS[6]).error,/two occupied/);
const split=judge([fish('bangus',120,240),fish('tilapia',370,240)],LEVELS[6],[],[],true,figure);
assert.equal(split.error,undefined);assert.equal(split.guided.length,2);
assert.match(judge([fish()],LEVELS[0],[],[],true,[{x:0,y:0},{x:900,y:0},{x:900,y:900},{x:0,y:0}]).error,/snapped/);
assert.equal(LEVELS.length,8);
console.log('Aquarium: closure, fry, cord cuts, debris, schools, purity, tide, pickups, safe fish, figure eight, and length checks passed.');
